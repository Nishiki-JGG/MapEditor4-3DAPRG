"""独自生成画像を携帯端末向けの色RGB＋浅い凹凸Aへ梱包する。Pillow / numpy。"""
import argparse
import base64
from pathlib import Path
import numpy as np
from PIL import Image

p=argparse.ArgumentParser()
p.add_argument('source',type=Path,help='独自に生成した岩盤画像（参照写真は不可）')
args=p.parse_args()
im=Image.open(args.source).convert('RGB').resize((512,512),Image.Resampling.LANCZOS)
rgb=np.asarray(im).astype(float)/255
luma=rgb@np.array([.2126,.7152,.0722])
alpha=np.uint8(np.clip(.45+(luma-.45)*.6,0,1)*255)
out=Image.merge('RGBA',(*im.split(),Image.fromarray(alpha)))
target=Path(__file__).resolve().parents[1]/'terrain'/'bedrock.png'
out.save(target,optimize=True)
data=base64.b64encode(target.read_bytes()).decode('ascii')
target.with_name('bedrock-data.js').write_text("// Generated by tools/pack-bedrock.py; original image, packed RGBA.\nwindow.TDBedrockData='data:image/png;base64,"+data+"';\n",encoding='utf-8')
print(f'{target.name}: {target.stat().st_size} bytes; mipmapped RGBA8 = 1398100 bytes')
